/**
 * The generator behind `operations.gen.ts` (#213).
 *
 * A pure function: generated sources in, module text out, no filesystem. The
 * thin CLI in `scripts/generate-operations.ts` reads the files, calls this, and
 * writes the result inside `src/generated` so the existing regeneration diff
 * gate covers it like every other artifact in the chain.
 *
 * It reads hey-api's OWN output rather than re-parsing `api/openapi.yaml`: the
 * operationId `showCLIReauthTransaction` becomes the function `show`+`Cli`+...,
 * a run-of-caps mangling this generator refuses to reimplement. Taking the
 * function names from `sdk.gen.ts` and the response shape from `types.gen.ts`
 * keeps that mangling in exactly one tool, and referencing the real symbols
 * makes the result a CHECKED registry - it stops compiling the day a name
 * drifts, which is the failure we want loud.
 */

/**
 * SCIM protocol endpoints hey-api emits with no response type or Zod schema
 * (bulk, /Me, and the two search POSTs). They are not SPA-consumed and have no
 * `z<Op>Response` to bind, so they carry no descriptor. Any OTHER function that
 * lacks a response is a generator drift and must fail loud, never be skipped.
 */
const KNOWN_RESPONSELESS = new Set(['scimBulk', 'scimMe', 'scimSearchUsers', 'scimSearchGroups']);

type SuccessResponse = { statuses: readonly number[]; bodyless: boolean };

/** pascal capitalises the first character - the shared base hey-api names share. */
function pascal(fn: string): string {
  return fn.charAt(0).toUpperCase() + fn.slice(1);
}

/** sdkFunctions extracts every exported operation function name from sdk.gen.ts. */
function sdkFunctions(sdkSource: string): string[] {
  const functions: string[] = [];
  for (const match of sdkSource.matchAll(/^export const (\w+) = <ThrowOnError/gm)) {
    const name = match[1];
    if (name === undefined) {
      throw new Error('sdk operation export matched without a function name');
    }
    functions.push(name);
  }
  return functions;
}

/**
 * sseFunctions names the streaming operations - hey-api emits these as `.sse.`
 * calls returning a ServerSentEventsResult, not the awaited `{ data, response }`
 * a `parsed`/`ok` descriptor consumes. They receive their own descriptor shape
 * so the stream call, handshake status, and event parser remain bound.
 */
function sseFunctions(sdkSource: string): Set<string> {
  const functions = new Set<string>();
  for (const match of sdkSource.matchAll(/^export const (\w+) = <ThrowOnError.*\.sse\./gm)) {
    const name = match[1];
    if (name === undefined) {
      throw new Error('streaming SDK operation matched without a function name');
    }
    functions.add(name);
  }
  return functions;
}

/**
 * successResponse reads the `<Base>Responses` block from types.gen.ts and
 * returns every 2xx status and whether all of them are `void` (bodyless).
 * Returns null when there is no such block - the caller decides whether that
 * is a known SCIM skip or a drift to shout about. A mixed body/bodyless set
 * cannot have one honest parser contract and therefore fails generation.
 */
function successResponse(typesSource: string, base: string): SuccessResponse | null {
  const block = new RegExp(`export type ${base}Responses = \\{([\\s\\S]*?)\\n\\};`).exec(
    typesSource,
  );
  if (block === null) {
    return null;
  }
  const responseBlock = block[1];
  if (responseBlock === undefined) {
    throw new Error(`${base}Responses matched without a response block`);
  }
  const successes: { status: number; body: string }[] = [];
  for (const match of responseBlock.matchAll(/^\s*(\d{3}):\s*(.+?);/gm)) {
    const statusText = match[1];
    const body = match[2];
    if (statusText === undefined || body === undefined) {
      throw new Error(`${base}Responses contained an incomplete status entry`);
    }
    const status = Number(statusText);
    if (Math.trunc(status / 100) === 2) {
      successes.push({ status, body: body.trim() });
    }
  }
  successes.sort((a, b) => a.status - b.status);
  const bodyless = successes.filter((entry) => entry.body === 'void');
  if (bodyless.length !== 0 && bodyless.length !== successes.length) {
    throw new Error(
      `${base} mixes body-bearing and bodyless success statuses; generate separate descriptors instead of weakening the parser contract`,
    );
  }
  if (successes.length === 0) {
    return null;
  }
  return {
    statuses: successes.map((entry) => entry.status),
    bodyless: bodyless.length === successes.length,
  };
}

/** hasZodResponse confirms the response parser a body operation will reference exists. */
function hasZodResponse(zodSource: string, base: string): boolean {
  return new RegExp(`^export const z${base}Response =`, 'm').test(zodSource);
}

const HEADER = `// This file is auto-generated by scripts/generate-operations.ts (#213).
// It binds each generated operation to its success status and response parser so
// the SPA selects an operation instead of pairing a promise and a schema by
// hand. Do not edit; regenerate via \`pnpm run generate\`.
`;

const DESCRIPTOR_TYPES = `import type { ZodType } from 'zod';

import type { RequestResult, TDataShape } from './client/index.ts';
import type { Options } from './sdk.gen.ts';

export type { TDataShape } from './client/index.ts';
export type { Options } from './sdk.gen.ts';

type NonThrowingResult<TResult> = TResult extends { error: infer _TError } ? TResult : never;

export type SdkResult = NonThrowingResult<Awaited<RequestResult>>;

type SdkCall<TData extends TDataShape> = (
  options: Options<TData, false>
) => Promise<SdkResult>;
type StreamCall = (...args: never[]) => Promise<object>;

// Module-private classes make construction inaccessible. Their ECMAScript
// private fields are also absent from object spreads, so a caller cannot clone
// a valid descriptor and replace its call or parser while retaining the brand.
class GeneratedBodyOperation<TData extends TDataShape, TSchema extends ZodType> {
  readonly #brand = 'body';

  constructor(
    readonly call: SdkCall<TData>,
    readonly successStatuses: readonly number[],
    readonly response: TSchema,
  ) {}
}

class GeneratedBodylessOperation<TData extends TDataShape> {
  readonly #brand = 'bodyless';

  constructor(
    readonly call: SdkCall<TData>,
    readonly successStatuses: readonly number[],
  ) {}
}

class GeneratedStreamOperation<TCall extends StreamCall, TSchema extends ZodType> {
  readonly #brand = 'stream';

  constructor(
    readonly call: TCall,
    readonly successStatuses: readonly number[],
    readonly response: TSchema,
  ) {}
}

export type BodyOperation<TData extends TDataShape, TSchema extends ZodType> =
  GeneratedBodyOperation<TData, TSchema>;
export type BodylessOperation<TData extends TDataShape> = GeneratedBodylessOperation<TData>;
export type StreamOperation<TCall extends StreamCall, TSchema extends ZodType> =
  GeneratedStreamOperation<TCall, TSchema>;
`;

/**
 * buildOperationsModule emits the operation registry as module text: one branded
 * descriptor per operation, deterministically ordered by function name.
 */
export function buildOperationsModule(input: {
  sdkSource: string;
  typesSource: string;
  zodSource: string;
}): string {
  const functions = [...sdkFunctions(input.sdkSource)].sort((a, b) => a.localeCompare(b, 'en'));
  const streaming = sseFunctions(input.sdkSource);

  const bodyFns: { fn: string; base: string; statuses: readonly number[] }[] = [];
  const bodylessFns: { fn: string; statuses: readonly number[] }[] = [];
  const streamFns: { fn: string; base: string; statuses: readonly number[] }[] = [];

  for (const fn of functions) {
    const base = pascal(fn);
    const success = successResponse(input.typesSource, base);
    if (success === null) {
      if (KNOWN_RESPONSELESS.has(fn)) {
        continue;
      }
      throw new Error(
        `operation ${fn} has no ${base}Responses in types.gen.ts and is not a known SCIM skip - the generator is out of step with hey-api's output`,
      );
    }
    if (streaming.has(fn)) {
      if (success.bodyless || !hasZodResponse(input.zodSource, base)) {
        throw new Error(`streaming operation ${fn} must have a body parser`);
      }
      streamFns.push({ fn, base, statuses: success.statuses });
      continue;
    }
    if (success.bodyless) {
      bodylessFns.push({ fn, statuses: success.statuses });
      continue;
    }
    if (!hasZodResponse(input.zodSource, base)) {
      throw new Error(
        `operation ${fn} is body-bearing but z${base}Response is missing from zod.gen.ts`,
      );
    }
    bodyFns.push({ fn, base, statuses: success.statuses });
  }

  const bases = [
    ...bodyFns.map((o) => o.base),
    ...bodylessFns.map((o) => pascal(o.fn)),
    ...streamFns.map((o) => o.base),
  ];
  const sdkImports = [
    ...bodyFns.map((o) => o.fn),
    ...bodylessFns.map((o) => o.fn),
    ...streamFns.map((o) => o.fn),
  ].sort((a, b) => a.localeCompare(b, 'en'));
  const typeImports = bases.map((base) => `${base}Data`).sort((a, b) => a.localeCompare(b, 'en'));
  const zodImports = [...bodyFns, ...streamFns]
    .map((o) => `z${o.base}Response`)
    .sort((a, b) => a.localeCompare(b, 'en'));

  const lines: string[] = [HEADER, DESCRIPTOR_TYPES];
  lines.push('import {');
  for (const name of sdkImports) {
    lines.push(`  ${name},`);
  }
  lines.push("} from './sdk.gen.ts';");
  lines.push('import type {');
  for (const name of typeImports) {
    lines.push(`  ${name},`);
  }
  lines.push("} from './types.gen.ts';");
  lines.push('import {');
  for (const name of zodImports) {
    lines.push(`  ${name},`);
  }
  lines.push("} from './zod.gen.ts';");
  lines.push('');

  for (const op of bodyFns) {
    lines.push(
      `export const ${op.fn}Op: BodyOperation<${op.base}Data, typeof z${op.base}Response> = /* @__PURE__ */ new GeneratedBodyOperation(${op.fn}, [${op.statuses.join(', ')}], z${op.base}Response);`,
    );
  }
  for (const op of bodylessFns) {
    const base = pascal(op.fn);
    lines.push(
      `export const ${op.fn}Op: BodylessOperation<${base}Data> = /* @__PURE__ */ new GeneratedBodylessOperation(${op.fn}, [${op.statuses.join(', ')}]);`,
    );
  }
  for (const op of streamFns) {
    lines.push(
      `export const ${op.fn}Op: StreamOperation<typeof ${op.fn}, typeof z${op.base}Response> = /* @__PURE__ */ new GeneratedStreamOperation(${op.fn}, [${op.statuses.join(', ')}], z${op.base}Response);`,
    );
  }
  lines.push('');

  return lines.join('\n');
}
